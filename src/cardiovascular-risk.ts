const MMOL = 0.02586; // mg/dL -> mmol/L, as in preventr

function preventTerms(x: CardiovascularRiskInput, model: PreventModel, years: 10 | 30): number[] {
  const age = (x.age - 55) / 10;
  const nonHdl = (x.totalC - x.hdlC) * MMOL - 3.5;
  const hdl = (x.hdlC * MMOL - 1.3) / 0.3;
  const sbpLt = (Math.min(x.sbp, 110) - 110) / 20;
  const sbpGte = (Math.max(x.sbp, 110) - 130) / 20;
  const bmi = x.bmi ?? 25; // only HF uses BMI; it is null without one
  const bmiLt = (Math.min(bmi, 30) - 25) / 5;
  const bmiGte = (Math.max(bmi, 30) - 30) / 5;
  const egfrLt = (Math.min(x.egfr, 60) - 60) / -15;
  const egfrGte = (Math.max(x.egfr, 60) - 90) / -15;
  const [dm, smk, bp, st] = [x.diabetes, x.smoker, x.bpTx, x.statin].map(Number);
  const a1c = x.hba1c === undefined ? 0 : x.hba1c - 5.3;
  return [age, ...(years === 30 ? [age * age] : []), nonHdl, hdl, sbpLt, sbpGte, dm, smk, bmiLt, bmiGte, egfrLt, egfrGte, bp, st,
    bp * sbpGte, st * nonHdl, age * nonHdl, age * hdl, age * sbpGte, age * dm, age * smk, age * bmiGte, age * egfrLt,
    ...(model === 'full' ? [0, 0, 1] : []), // no SDI: missing
    ...(model === 'uacr' || model === 'full' ? [Math.log(x.uacr as number), 0] : []),
    ...(model === 'hba1c' || model === 'full' ? [dm ? 0 : a1c, dm ? a1c : 0, 0] : []), 1];
}

const logistic = (coef: number[], terms: number[]) => {
  const lo = coef.reduce((s, c, i) => s + c * terms[i], 0);
  return Math.exp(lo) / (1 + Math.exp(lo));
};

function pce(x: CardiovascularRiskInput): number {
  const [la, lt, lh, ls] = [x.age, x.totalC, x.hdlC, x.sbp].map(Math.log);
  const [s, d] = [Number(x.smoker), Number(x.diabetes)];
  const black = x.race === 'black';
  if (x.sex === 'female') {
    return black
      ? 1 - 0.9533 ** Math.exp(17.114 * la + 0.94 * lt - 18.92 * lh + 4.475 * la * lh + (x.bpTx ? 29.291 : 27.82) * ls + (x.bpTx ? -6.432 : -6.087) * la * ls + 0.691 * s + 0.874 * d - 86.6081)
      : 1 - 0.9665 ** Math.exp(-29.799 * la + 4.884 * la ** 2 + 13.54 * lt - 3.114 * la * lt - 13.578 * lh + 3.149 * la * lh + (x.bpTx ? 2.019 : 1.957) * ls + 7.574 * s - 1.665 * la * s + 0.661 * d + 29.1817);
  }
  return black
    ? 1 - 0.8954 ** Math.exp(2.469 * la + 0.302 * lt - 0.307 * lh + (x.bpTx ? 1.916 : 1.809) * ls + 0.549 * s + 0.645 * d - 19.5425)
    : 1 - 0.9144 ** Math.exp(12.344 * la + 11.853 * lt - 2.664 * la * lt - 7.99 * lh + 1.769 * la * lh + (x.bpTx ? 1.797 : 1.764) * ls + 7.837 * s - 1.795 * la * s + 0.658 * d - 61.1816);
}

// Validity ranges as enforced by preventr; out-of-range inputs give null with a note instead of an extrapolation.
export function cardiovascularRisk10yr(x: CardiovascularRiskInput): CardiovascularRiskResult {
  const notes: string[] = [];
  const inRange = (v: number, lo: number, hi: number, name: string) => (v >= lo && v <= hi) || (notes.push(`${name} ${v} outside ${lo}-${hi}`), false);
  const common = inRange(x.totalC, 130, 320, 'total cholesterol') && inRange(x.hdlC, 20, 100, 'HDL') && inRange(x.sbp, 90, 180, 'SBP');
  const preventOk = inRange(x.age, 30, 79, 'age (PREVENT)') && common && inRange(x.egfr, 15, 140, 'eGFR') &&
    (x.bmi === undefined || inRange(x.bmi, 18.5, 39.9, 'BMI'));
  const pceOk = inRange(x.age, 40, 79, 'age (PCE)') && common;
  if (!x.race) notes.push('race not given: PCE uses the white/other equation');
  if (x.statin) notes.push('PCE assumes no statin; its result ignores the statin input');
  // Like preventr, an out-of-range HbA1c or UACR is dropped and the model chosen from what is left.
  const p = { ...x };
  if (p.hba1c !== undefined && !inRange(p.hba1c, 4.5, 15, 'HbA1c')) delete p.hba1c;
  if (p.uacr !== undefined && !inRange(p.uacr, 0.1, 25000, 'UACR')) delete p.uacr;
  const model: PreventModel = p.hba1c !== undefined ? (p.uacr !== undefined ? 'full' : 'hba1c') : p.uacr !== undefined ? 'uacr' : 'base';
  const hfOk = preventOk && x.bmi !== undefined;
  if (preventOk && !hfOk) notes.push('BMI not given: PREVENT heart failure needs it');
  const ok30 = preventOk && x.age <= 59;
  if (preventOk && !ok30) notes.push('30-year PREVENT not given: estimating 30-year risk in people > 59 years of age is questionable (preventr)');
  const risk = (years: 10 | 30, outcome: Outcome) => logistic(PREVENT[`${model}_${years}yr`][x.sex][outcome], preventTerms(p, model, years));
  return {
    preventAscvd: preventOk ? risk(10, 'ascvd') : null,
    preventTotalCvd: preventOk ? risk(10, 'totalCvd') : null,
    pce: pceOk ? pce(x) : null,
    notes,
    preventHeartFailure: hfOk ? risk(10, 'hf') : null,
    preventAscvd30yr: ok30 ? risk(30, 'ascvd') : null,
    preventTotalCvd30yr: ok30 ? risk(30, 'totalCvd') : null,
    preventHeartFailure30yr: ok30 && hfOk ? risk(30, 'hf') : null,
    preventModel: preventOk ? model : null,
  };
}
